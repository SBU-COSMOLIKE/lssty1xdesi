"""Defines the Cobaya likelihood lssty1xdesi.desi_cl (DESI spectroscopic
angular clustering band powers).

The entry `lssty1xdesi.desi_cl` in the likelihood block of a yaml file
makes Cobaya import this module and build the class of the same name,
with the options and defaults of desi_cl.yaml (next to this file). The
data vector is the DESI-DR3 thin-bin forecast: 76 tomographic bins of
equal comoving width (18 BGS + 31 LRG + 27 ELG), each an angular
clustering auto spectrum in band powers of width Delta ell = 10, read
together with its Gaussian covariance and per-bin scale-cut mask from
the files make_desi_dataset.py imported out of the group's sacc file.
Cross-bin spectra have no slot yet (the cross wiring is a held design
discussion); their information is simply absent from the data vector.

The base class _cosmolike_prototype_base does the heavy lifting in its
fourier mode (binning_space: fourier): band centers from the dataset's
ell_file, init_data_fourier, and the Fourier 3x2pt data vector, of
which this probe ("wtheta") fills the clustering block alone. This
subclass adds the two pieces of DESI-specific physics, both applied at
every sampled point:

  galaxy bias - one sampled amplitude per bias chunk (BGS, LRG1-3,
    ELG1-2; the paper's Table 2 ranges), with the per-bin linear bias
    b1_i = amplitude / D(zbar_i): the amplitude is the bias at z = 0 in
    a constant-clustering-amplitude evolution (b D fixed; not the
    passive evolution of a conserved population, b - 1 ~ 1/D), and D(zbar_i)
    is the linear growth at the bin's mean redshift, measured from the
    linear P(k) ratio at one large scale where growth is scale
    independent;

  Fingers of God - each thin bin's distribution is the raw histogram
    convolved with a Gaussian in redshift of width
    sigma_z,i = (1 + zbar_i) sigma_v / c, where sigma_v (km/s) is
    sampled once per sample (BGS, LRG, ELG): a line-of-sight peculiar
    velocity v shifts an observed redshift by (1 + z) v / c, and the
    bins are far narrower than the dispersion's effect, which is what
    makes the convolution the dominant small-scale radial systematic
    (the paper's eq. 20). The convolved distributions reach cosmolike
    through the external-n(z) path (set_lens_sample), so the raw
    histograms on disk are never modified.

With higher_order_bias: 1 the bias is model A of notes/higher_order_bias
(the physics reference; see its recommendation section), for the
k_max = 0.075 h/Mpc analysis:

  one-loop real-space bias - per bin, the quadratic and tidal biases
    follow that bin's own b1 through calibrated relations, plus offsets:
        b2_i  = b2_Lazeyras(b1_i) + DESI_DB2_i,
        bs2_i = -(4/7) (b1_i - 1)  + DESI_DBS_i,
    with b2_Lazeyras the separate-universe fit of arXiv:1511.01096 and
    the co-evolution tidal bias, both in the CCL/FAST-PT normalization
    cosmolike uses; b3 = 0;

  counterterm - alpha_0 k^2 P per bin (DESI_A0_i, in h^-2 Mpc^2), passed
    as cosmolike's k^2 bias term, which enters P_gg as 2 b1 bK k^2 P_delta
    with k in units of H0/c: bK_i = alpha_0,i / (2 b1_i (c/H0)^2);

  stochastic term - a white-noise 3D power s0_i P_Pois,i per bin
    (DESI_SN0_i, in units of the bin's Poisson power P_Pois,i), the
    deviation from Poisson (the Poisson part sits in the covariance). A
    constant power projects exactly (no Limber approximation) to
        C^ij = P_ij * integral dchi W_i W_j / chi^2,
    independent of ell, with W the Fingers-of-God-convolved kernels, so
    adjacent bins of one tracer sample whose kernels overlap get a cross
    term too (the mean of the two bins' powers); pairs of two different
    samples get none. P_Pois,i = 1/nbar_i, with
    the 3D density nbar_i fixed by the bin's surface density
    (<dataset stem>_ngal.txt): the raw-histogram projection of 1/nbar_i
    is exactly the angular shot noise 1/n_2D,i.

Like the linear bias, every model A parameter is per bin; groups (one
offset per chunk, or an offset plus a tilt in redshift) are yaml
statements (likelihood/params_desi*_model_a.yaml, generated by
scripts/make_desi_params.py --model-a).
"""
import os

import numpy as np
from cobaya.likelihoods.lssty1xdesi._cosmolike_prototype_base import \
    _cosmolike_prototype_base
from cobaya.log import LoggedError
from getdist import IniFile
from scipy.interpolate import CubicSpline
from scipy.ndimage import gaussian_filter1d

import cosmolike_lssty1xdesi_interface as ci

# speed of light in km/s: a line-of-sight peculiar velocity v shifts the
# observed redshift by (1 + z) v / c, so a velocity dispersion sigma_v
# becomes a redshift dispersion sigma_z = (1 + zbar) sigma_v / c
C_KMS = 299792.458

# The nuisance parameters are PER BIN: DESI_B1_<n> and DESI_SIGV_<n>,
# n = 1..lens_ntomo in the bin-table order. This likelihood knows
# nothing about parameter groupings - a group (per Table-2 chunk, per
# sample, or any other model) is a yaml statement: the group's first
# bin carries the prior and every other member is tied to it with a
# cobaya value function (see likelihood/params_desi.yaml, generated by
# scripts/make_desi_params.py). The sampler then sees one degree of
# freedom per group, and changing the grouping never touches code.

# the large scale [1/Mpc] where D(z) is read off the linear P(k) ratio;
# growth is scale independent there to far better than the sub-percent
# level even with massive neutrinos
KREF = 5.0e-3

# model A (higher_order_bias: 1). c/H0 in Mpc/h: cosmolike's wavenumbers
# are in units of H0/c, so alpha_0 k^2 with k in h/Mpc is
# alpha_0/(c/H0)^2 k^2 in cosmolike units
C_OVER_H0 = C_KMS/100.0
# a surface density per arcmin^2 times this is per steradian
ARCMIN2_PER_SR = (180.0*60.0/np.pi)**2

# The unit of the line-of-sight stochastic power SN_2 k^2 mu^2 (model B),
# in (Mpc/h)^2 before the Poisson factor: f_sat sigma_v^2, the satellite
# fraction times the squared velocity dispersion of the satellites in
# distance units, the DESI DR1 scaling of SN_2 (Maus et al.,
# arXiv:2404.07312, their stochastic-prior table). That table gives LRG
# (f_sat = 0.1, sigma_v = 7.8 Mpc/h) and ELG (0.1, 2.9 Mpc/h) and has no
# BGS row; BGS takes the LRG values, the larger unit and so the wider prior.
SN2_UNIT = {"bgs": 0.1*7.8**2, "lrg": 0.1*7.8**2, "elg": 0.1*2.9**2}


def lazeyras_b2(b1):
  """The separate-universe b2(b1) fit of Lazeyras et al. (arXiv:1511.01096).

  Arguments:
    b1 = Eulerian linear bias (scalar or numpy array).

  Returns:
    b2 in the CCL/FAST-PT normalization (the quadratic operator carries
    a factor 1/2 in the galaxy overdensity), the one cosmolike uses.
  """
  return 0.412 - 2.143*b1 + 0.929*b1**2 + 0.008*b1**3


class desi_cl(_cosmolike_prototype_base):
  """Evaluates the DESI thin-bin clustering likelihood (probe "wtheta")."""

  def initialize(self):
    """Configure the base for the Fourier clustering-only probe.

    Cobaya calls initialize once. super(...) runs the base initialize,
    which reads the .dataset file, sets up cosmolike in fourier mode and
    loads the data vector, covariance and mask; this override then reads
    the bin table (sample, bias chunk and mean redshift of each thin
    bin) and prepares the chunk-to-bin parameter maps.

    Raises:
      LoggedError when the dataset is not in fourier mode, when the
      external-n(z) path is off (the FoG convolution needs it), or when
      the bin table does not cover every lens bin.
    """
    super(desi_cl, self).initialize(probe="wtheta")
    if self.binning_space != "fourier":
      raise LoggedError(
          self.log, "desi_cl needs binning_space: fourier (the data "
          "vector is band powers; got %s)", self.binning_space)
    if not self.external_nz_modeling:
      raise LoggedError(
          self.log, "desi_cl needs external_nz_modeling: 1 - the "
          "Fingers-of-God convolution rebuilds the n(z) at every point")
    if self.use_baryon_pca or self.create_baryon_pca:
      raise LoggedError(
          self.log, "the baryon principal components live on the "
          "real-space data vector; no fourier counterpart exists")

    # the bin table written by make_desi_nz.py, named by the dataset:
    # one row per thin bin with its sample, chunk and mean redshift.
    # Only the mean redshifts are read here - the parameters are per
    # bin, so no chunk-to-parameter map exists (see the module note)
    ini = IniFile(os.path.normpath(os.path.join(self.path, self.data_file)))
    table_file = ini.relativeFileName("lens_bin_table")
    self.desi_zbar = np.atleast_1d(np.loadtxt(table_file, usecols=4))
    if len(self.desi_zbar) != int(self.lens_ntomo):
      raise LoggedError(
          self.log, "the bin table lists %d bins; the dataset declares "
          "lens_ntomo = %d", len(self.desi_zbar), int(self.lens_ntomo))

    # the n(z) table the base read for the external-n(z) path: column 0
    # is the shared redshift grid, column i + 1 the raw histogram of bin
    # i; the FoG kernel width is expressed in steps of this grid
    zgrid = np.asarray(self.lens_nz)[:, 0]
    dz = np.diff(zgrid)
    # 1e-6 relative: far looser than any text-format rounding of the
    # grid (12 printed digits leave ~1e-9 relative wobble) and far
    # tighter than anything that could move a kernel of ~4 grid steps
    if not np.all(dz > 0) or np.max(np.abs(dz - dz[0])) > 1.0e-6 * dz[0]:
      raise LoggedError(
          self.log, "the lens n(z) grid must be uniform and increasing "
          "(the Gaussian FoG kernel works in grid steps)")
    self.desi_dz = float(dz[0])

    # the theory vector of the last evaluation, with every term this
    # likelihood adds (the Fisher module reads it instead of the
    # compiled-interface vector, which lacks the stochastic term)
    self.last_datavector = None
    self.desi_lens_nz_fog = None
    self.higher_order_bias = int(getattr(self, "higher_order_bias", 0))
    if self.higher_order_bias not in (0, 1):
      raise LoggedError(
          self.log, "higher_order_bias = %d: 0 (linear bias) and 1 "
          "(model A) are the options", self.higher_order_bias)
    if self.higher_order_bias == 1:
      # model A hands cosmolike b2, bs2, b3 = 0 and bK per bin, so every
      # bias code must read its per-bin slot: code 1 of b3 (b3 = b1 - 1)
      # or of bs2 would silently replace what this likelihood passes
      if [int(code) for code in self.bias_model] != [0]*6:
        raise LoggedError(
            self.log, "higher_order_bias: 1 needs bias_model: "
            "[0,0,0,0,0,0] (b2, bs2, b3 and bK per bin; model A sets "
            "b3 = 0); got %s", list(self.bias_model))
      # the surface densities of the bins, the unit of the stochastic
      # amplitudes: <stem>_ngal.txt beside <stem>_bins.txt, the naming
      # of the dataset generators and the covariance adapter
      if not table_file.endswith("_bins.txt"):
        raise LoggedError(
            self.log, "model A reads the bin densities from "
            "<stem>_ngal.txt next to the bin table <stem>_bins.txt; got "
            "the bin table %s", table_file)
      ngal_file = table_file[:-len("_bins.txt")] + "_ngal.txt"
      ngal = np.atleast_1d(np.loadtxt(ngal_file, usecols=1))
      if len(ngal) != int(self.lens_ntomo):
        raise LoggedError(
            self.log, "%s lists %d bins; the dataset declares lens_ntomo "
            "= %d", ngal_file, len(ngal), int(self.lens_ntomo))
      self.desi_ngal_sr = ngal*ARCMIN2_PER_SR
      # the tracer sample of every bin (bgs, lrg, elg): the stochastic
      # term of a cross pair exists only inside one sample
      self.desi_sample = np.atleast_1d(
          np.loadtxt(table_file, usecols=1, dtype=str))
      self.desi_dv_layout = None  # built at the first evaluation

  # ------------------------------------------------------------------------
  # ------------------------------------------------------------------------
  # ------------------------------------------------------------------------

  def set_lens_related(self, **params):
    """Send the DESI nuisance parameters of this point to cosmolike.

    Replaces the base implementation (LSST lens parameters) with the
    DESI model: per-bin linear bias from the sampled chunk amplitudes
    divided by the growth at each bin's mean redshift, the
    Fingers-of-God convolution of every raw thin-bin n(z) with the
    sample's sampled velocity dispersion, and zeros for every lens
    nuisance this forecast does not model (higher-order bias,
    magnification, point masses, photo-z shifts - spectroscopic
    redshifts carry no shift parameter).

    Every array crosses the compiled-interface boundary as a numpy
    array, never a plain Python list: the carma list-to-arma conversion
    of this environment silently zero-fills sequences longer than
    Armadillo's 16-element preallocation, and this project's lens
    arrays carry 76 entries (the 5-bin donor never saw the bug).

    Arguments:
      **params = the parameters of this point, as keyword arguments:
        DESI_B1_<n>   = bias amplitude of bin n (b1 at z = 0 under a
                        constant clustering amplitude b D),
                        n = 1..lens_ntomo;
        DESI_SIGV_<n> = velocity dispersion of bin n in km/s;
        with higher_order_bias: 1 also DESI_DB2_<n>, DESI_DBS_<n> and
        DESI_A0_<n> (see model_a_biases).
      Every per-bin parameter must be present: the yaml fragment
      declares all of them (group members tied to their leaders), so a
      missing one is a configuration error, reported by name.

    Side effects: changes cosmolike's nuisance parameters and replaces
    the lens n(z) of this point.
    """
    ntomo = int(self.lens_ntomo)
    zeros = np.zeros(ntomo)

    # growth at the bin means, normalized to z = 0, from the linear
    # P(k) the pipeline already requests (nonlinear=(True, False))
    pk = self.provider.get_Pk_interpolator(
        ("delta_tot", "delta_tot"), nonlinear=False)
    growth = np.sqrt(pk.P(self.desi_zbar, KREF) / pk.P(0.0, KREF))

    b1 = np.empty(ntomo)
    for i in range(ntomo):
      name = f"DESI_B1_{i + 1}"
      if name not in params:
        raise LoggedError(
            self.log, "%s is missing: every per-bin bias must be "
            "declared (likelihood/params_desi.yaml ties group members "
            "to their leaders)", name)
      b1[i] = float(params[name]) / float(growth[i])
    if not np.all(np.isfinite(b1)) or not np.all(b1 > 0):
      raise LoggedError(
          self.log, "per-bin b1 must be finite and positive; got "
          "b1[:3] = %s from growth[:3] = %s at zbar[:3] = %s",
          b1[:3], np.asarray(growth)[:3], self.desi_zbar[:3])

    ci.set_point_mass(PMV=zeros)
    if self.higher_order_bias == 1:
      b2, bs2, bk = self.model_a_biases(b1, params)
      ci.set_nuisance_bias_tidal(B1=b1, B2=b2, BS2=bs2, B_MAG=zeros,
                                 B3nl=zeros, BK=bk)
    else:
      ci.set_nuisance_bias(B1=b1, B2=zeros, B_MAG=zeros,
                           B3nl=zeros, BK=zeros)

    # Fingers of God: convolve a COPY of each raw histogram (self.lens_nz
    # must keep the file's distributions for the next point).
    # gaussian_filter1d smooths with a Gaussian whose width is given in
    # grid steps; mode="constant" treats the distribution as zero beyond
    # the grid, which is what a histogram that ends there means.
    lens_nz_local = np.asarray(self.lens_nz).copy()
    for i in range(ntomo):
      name = f"DESI_SIGV_{i + 1}"
      if name not in params:
        raise LoggedError(
            self.log, "%s is missing: every per-bin velocity "
            "dispersion must be declared (likelihood/params_desi.yaml "
            "ties group members to their leaders)", name)
      sigma_v = float(params[name])
      sigma_z = (1.0 + float(self.desi_zbar[i])) * sigma_v / C_KMS
      lens_nz_local[:, i + 1] = gaussian_filter1d(
          lens_nz_local[:, i + 1], sigma=sigma_z / self.desi_dz,
          mode="constant")
    ci.set_lens_sample(lens_nz_local)
    # the kernels of this point, which the stochastic term projects
    self.desi_lens_nz_fog = lens_nz_local

    # spectroscopic redshifts: no photo-z shift is modeled, but the
    # setter must run so a value left by another likelihood in the same
    # process cannot survive
    ci.set_nuisance_clustering_photoz(bias=zeros)

  # ------------------------------------------------------------------------
  # ------------------------------------------------------------------------
  # ------------------------------------------------------------------------

  def per_bin_values(self, prefix, params):
    """The per-bin values of one parameter family, in bin order.

    Arguments:
      prefix = the family's name prefix, e.g. "DESI_DB2"; bin n (1-based)
               reads <prefix>_<n>.
      params = the point's parameters (logp's keyword arguments).

    Returns:
      float64 array of length lens_ntomo.

    Raises:
      LoggedError naming the first missing parameter: every member must
      be declared (the yaml fragment ties group members to leaders).
    """
    ntomo = int(self.lens_ntomo)
    out = np.empty(ntomo)
    for i in range(ntomo):
      name = f"{prefix}_{i + 1}"
      if name not in params:
        raise LoggedError(
            self.log, "%s is missing: higher_order_bias: 1 needs every "
            "per-bin model A parameter (likelihood/params_desi*_model_a"
            ".yaml ties group members to their leaders)", name)
      out[i] = float(params[name])
    return out

  def model_a_biases(self, b1, params):
    """The per-bin b2, bs2 and bK of model A at one point.

    The quadratic and tidal biases follow each bin's own b1 (the full
    per-bin value, so they drift with it) through the calibrated
    relations, plus the per-bin offsets DESI_DB2_<n> and DESI_DBS_<n>.
    The counterterm DESI_A0_<n> = alpha_0 [h^-2 Mpc^2] multiplies
    k^2 P(k); cosmolike's k^2 term is 2 b1 bK k^2 P_delta with k in
    units of H0/c, hence bK = alpha_0 / (2 b1 (c/H0)^2).

    Arguments:
      b1     = the per-bin linear biases of this point.
      params = the point's parameters.

    Returns:
      (b2, bs2, bk): three float64 arrays of length lens_ntomo.
    """
    b2 = lazeyras_b2(b1) + self.per_bin_values("DESI_DB2", params)
    bs2 = -4.0/7.0*(b1 - 1.0) + self.per_bin_values("DESI_DBS", params)
    alpha0 = self.per_bin_values("DESI_A0", params)
    bk = alpha0/(2.0*b1*C_OVER_H0**2)
    return b2, bs2, bk

  def stochastic_templates(self, order=0):
    """The derivative of the theory vector with respect to every DESI_SN0_<n>
    (order = 0) or DESI_SN2_<n> (order = 2).

    Order 0. The stochastic power of bin i is s0_i P_Pois,i
    (s0_i = DESI_SN0_i), constant in k, so it projects exactly to an
    ell-independent
        C^ij = P_ij K_ij,   K_ij = integral dchi W_i W_j / chi^2
             = integral dz n_i(z) n_j(z) (dz/dchi) / chi^2,
    with n the normalized Fingers-of-God-convolved distributions of the
    last evaluated point, chi the comoving distance in Mpc/h, and
    P_ij = (P_i + P_j)/2 for a cross pair inside one tracer sample; a
    pair of two samples (an LRG and an ELG bin at the same redshift, say)
    gets none, since different galaxies share no stochastic term. The
    unit P_Pois,i = 1/nbar_i
    is set by the bin's surface density n_2D,i [sr^-1]: projected with
    the raw histogram it must give the angular shot noise 1/n_2D,i, so
    P_Pois,i = 1/(n_2D,i K_ii^raw).

    Order 2. The line-of-sight stochastic power s2_i U_i k^2 mu^2
    (s2_i = DESI_SN2_i, U_i = f_sat sigma_v^2 P_Pois,i of the bin's
    sample, see SN2_UNIT) is the power of a field that is the radial
    derivative of white noise: k^2 mu^2 = k_par^2 is the Fourier image of
    the second radial derivative. Integrating by parts moves the
    derivative onto the kernel, so it projects exactly, like order 0,
    with each kernel replaced by its radial derivative:
        C^ij = U_ij K2_ij,   K2_ij = integral dchi W_i'(chi) W_j'(chi) / chi^2,
    with W_i(chi) = n_i(z) dz/dchi and W_i' = dW_i/dchi. The sharp edges
    of a thin bin, smoothed only by the Fingers-of-God convolution, set
    its size; adjacent bins of one sample get a cross term, negative where
    one kernel falls as the other rises.

    Arguments:
      order = 0 for SN0, 2 for SN2.

    Returns:
      float64 array [data-vector length, lens_ntomo], zero on masked
      entries: column i is d(theory)/d(DESI_SN0_i) or d(theory)/d(DESI_SN2_i).
    """
    if order not in (0, 2):
      raise LoggedError(self.log, "stochastic order %s: 0 or 2", order)
    if self.desi_lens_nz_fog is None:
      raise LoggedError(
          self.log, "stochastic_templates needs an evaluated point (the "
          "kernels come from the last set_lens_related)")
    if self.desi_dv_layout is None:
      # the data-vector blocks [EE, gs, gg, gg-cross] and the mask, fixed
      # once the dataset is loaded
      sizes = ci.compute_data_vector_fourier_with_gg_cross_sizes()
      self.desi_dv_layout = {
          "gg": int(sizes[0] + sizes[1]),
          "ggx": int(sizes[0] + sizes[1] + sizes[2]),
          "n": int(sum(sizes)),
          "mask": np.asarray(ci.get_mask(), dtype=bool)}
    layout = self.desi_dv_layout
    ntomo = int(self.lens_ntomo)
    ncl = len(self.band_ells)

    # chi(z) and dchi/dz on the n(z) grid, from the comoving distance the
    # base requests on z_interp_1D (Mpc, times h for Mpc/h)
    h = self.provider.get_param("H0")/100.0
    chi_spline = CubicSpline(
        self.z_interp_1D,
        self.provider.get_comoving_radial_distance(self.z_interp_1D)*h)
    z = np.asarray(self.lens_nz)[:, 0]
    chi = chi_spline(z)
    dchidz = chi_spline(z, 1)
    weight = np.zeros_like(z)
    live = chi > 0.0
    weight[live] = 1.0/(dchidz[live]*chi[live]**2)

    def normalized(table):
      n = np.array(table, dtype=np.float64)[:, 1:]
      return n/np.trapz(n, z, axis=0)

    n_fog = normalized(self.desi_lens_nz_fog)
    n_raw = normalized(self.lens_nz)
    k_raw = np.trapz(n_raw**2*weight[:, None], z, axis=0)
    p_pois = 1.0/(self.desi_ngal_sr*k_raw)

    if order == 0:
      # the projected profiles are the kernels themselves
      profile, measure, unit = n_fog, weight, p_pois
    else:
      # W_i(chi) = n_i(z) dz/dchi and its radial derivative
      # dW_i/dchi = (dW_i/dz)/(dchi/dz); np.gradient takes second-order
      # centered differences on the uniform z grid
      kernel = np.zeros_like(n_fog)
      kernel[live] = n_fog[live]/dchidz[live, None]
      profile = np.gradient(kernel, z, axis=0)
      profile[live] /= dchidz[live, None]
      # integral dchi f / chi^2 = integral dz (dchi/dz) f / chi^2
      measure = np.zeros_like(z)
      measure[live] = dchidz[live]/chi[live]**2
      unit = p_pois*np.array([SN2_UNIT[str(s)] for s in self.desi_sample])
    k_auto = np.trapz(profile**2*measure[:, None], z, axis=0)

    templates = np.zeros((layout["n"], ntomo))
    for i in range(ntomo):
      rows = layout["gg"] + ncl*i + np.arange(ncl)
      templates[rows, i] = unit[i]*k_auto[i]
    if self.gg_cross_pairs is not None:
      for m, (i, j) in enumerate(np.asarray(self.gg_cross_pairs, dtype=int)):
        if self.desi_sample[i] != self.desi_sample[j]:
          # two tracer samples are different galaxies: their Poisson
          # cross noise is zero, and a non-Poisson cross stochasticity
          # would be a parameter of its own, not either sample's s0
          continue
        k_ij = np.trapz(profile[:, i]*profile[:, j]*measure, z)
        rows = layout["ggx"] + ncl*m + np.arange(ncl)
        templates[rows, i] += 0.5*unit[i]*k_ij
        templates[rows, j] += 0.5*unit[j]*k_ij
    templates[~layout["mask"]] = 0.0
    return templates

  def internal_get_datavector(self, **params):
    """The base's theory vector, plus model A's stochastic term.

    With higher_order_bias: 0 this is the base's vector unchanged (as a
    float64 array). Either way the result is kept in last_datavector.

    Arguments:
      **params = the point's parameters.

    Returns:
      1D float64 array of the full data-vector length; masked entries 0.
    """
    datavector = np.asarray(
        super(desi_cl, self).internal_get_datavector(**params),
        dtype=np.float64)
    if self.higher_order_bias == 1:
      s0 = self.per_bin_values("DESI_SN0", params)
      datavector = datavector + self.stochastic_templates() @ s0
      if self.print_datavector:
        # the base wrote its file before the stochastic term existed
        out = np.column_stack([np.arange(datavector.size), datavector])
        np.savetxt(self.print_datavector_file, out, fmt=('%d', '%1.8e'))
    self.last_datavector = datavector
    return datavector
